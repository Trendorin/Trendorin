#!/usr/bin/env python3
"""Builds README.md from profile.toml. Standard library only (Python 3.11+).

    python3 build.py
"""
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MARK = "<!-- generated by build.py from profile.toml: edit the config, not this file -->"


def icon(base: str) -> str:
    """An inline icon; with -Light and -Dark files it follows the viewer's theme."""
    light, dark = ROOT / f"assets/icons/{base}-Light.svg", ROOT / f"assets/icons/{base}-Dark.svg"
    img = lambda f: f'<img src="assets/icons/{f}" width="20" height="20" align="absmiddle">'
    if light.exists() and dark.exists():
        return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="assets/icons/{base}-Dark.svg">'
                f'{img(f"{base}-Light.svg")}</picture>')
    return img(f"{base}.svg")


def main() -> None:
    cfg = tomllib.loads((ROOT / "profile.toml").read_text())
    p = cfg["profile"]
    about = " ".join(p["about"].split())
    stack = "<br>\n".join(
        " ".join(icon(i) for i in s.get("icons", [])) + f' <b>{s["name"]}</b>, {s["note"]}' for s in cfg["stack"]
    )
    projects = "\n".join(
        f'<li><a href="https://github.com/{p["login"]}/{x["name"]}"><b>{x["name"]}</b></a>, {x["description"]}</li>'
        for x in cfg["projects"]
    )
    out = f"""{MARK}

<table><tr>
<td valign="top" width="400"><img src="assets/poster.png" width="384" alt="A moonlit meadow with fireflies"></td>
<td valign="top">

<h3>Hi, I'm {p["name"]}</h3>
<p>{about}</p>

<h3>Stack</h3>
<p>
{stack}
</p>

<h3>Projects</h3>
<ul>
{projects}
</ul>

</td>
</tr></table>
"""
    (ROOT / "README.md").write_text(out)
    print(f"README.md: {len(cfg['stack'])} stack items, {len(cfg['projects'])} projects")


if __name__ == "__main__":
    main()
