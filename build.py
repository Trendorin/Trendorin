def build(cfg, out: Path, live: dict, ci=False) -> list[str]:
    """Write README.md, SUPPORT.md, .github/* and assets/ into `out`. Returns TODO notes.
    Output depends only on the config, `live` and committed files under art/, so a CI
    rebuild is byte-identical unless a live value changed."""
    todo: list[str] = []
    p = cfg["profile"]
    login = p["login"]
    assets = out / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    written: set[str] = set()

    def svg2(name, make):
        for theme in THEMES:
            (assets / f"{name}-{theme}.svg").write_text(str(make(theme)))
            written.add(f"{name}-{theme}.svg")

    def pic(name, alt):
        return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="assets/{name}-dark.svg">'
                f'<img src="assets/{name}-light.svg" alt="{esc(alt)}"></picture>')

    def card(name, title, caption, logo, url, primary=False):
        svg2(name, lambda t: card_svg(title, caption, logo, t, primary))
        return f'<a href="{esc(url)}">{pic(name, f"{title}: {caption}")}</a>'

    svg2("header", lambda t: header_svg(p["title"], p["tagline"], t))
    md = [MARK, "", '<div align="center">', "", pic("header", f"{p['title']}: {p['tagline']}"), ""]
    sections = []

    sections.append(("About", ["\n".join(line.strip() for line in para.strip().splitlines())
                               for para in p.get("about", "").strip().split("\n\n") if para.strip()]))

    spec = []
    for r in cfg.get("spec", []):
        value = r.get("value") or live.get(r.get("live", ""), "")
        if r.get("key") and value:
            spec.append((r["key"], value))
        elif r.get("live"):
            todo.append(f"spec {r.get('key')}: no value for live source {r['live']!r} yet (run online once)")
    if spec:
        user, host = login.lower(), "github"
        height = spec_svg(user, host, spec, "dark", gap=0).h  # portrait matches the readout's height
        alt = f"{user}@{host}: " + "; ".join(f"{k}: {v}" for k, v in spec)
        svg2("spec", lambda t: spec_svg(user, host, spec, t, H=height))
        block = pic("spec", alt)
        portrait = ROOT / p.get("portrait", "art/portrait.png")
        if grid := portrait_grid(portrait, refresh=not ci):
            svg2("portrait", lambda t: portrait_svg(grid, t, f"{p.get('name', login)}, dithered portrait", H=height))
            block = pic("portrait", "Dithered portrait") + " " + block
        else:
            todo.append(f"{portrait.relative_to(ROOT)}: no portrait or cached grid (needs Pillow once): skipped")
        sections.append(("System", [block]))

    if projects := [x for x in cfg.get("projects", []) if x.get("name") and x.get("url")]:
        sections.append(("Projects", [" ".join(
            card(f"project-{slug(x['name'])}", x["name"], x.get("description", ""), "github", x["url"])
            for x in projects)]))

    row = [card("link-github", "GITHUB", f"github.com/{login}", "github", f"https://github.com/{login}?tab=repositories")]
    for key, (title, logo, fmt, caption, loud) in LINK_KINDS.items():
        value = cfg.get("links", {}).get(key, "").strip()
        if value:
            row.append(card(f"link-{key}", title, caption(value), logo, fmt.format(value)))
        elif loud:
            todo.append(f"links.{key} is empty: the {title.title()} card is hidden")
    sections.append(("Contact", [" ".join(row)]))

    sup = cfg.get("support", {})
    s_links = [l for l in sup.get("links", []) if l.get("url")]
    todo += [f"support: {l['label']} has no url: hidden" for l in sup.get("links", []) if not l.get("url")]
    if sup.get("github_sponsors"):
        s_links.insert(0, {"label": "Sponsor", "logo": "github", "caption": "GitHub Sponsors",
                           "url": f"https://github.com/sponsors/{login}", "note": "GitHub Sponsors, monthly or one-time"})
    crypto = [c for c in sup.get("crypto", []) if c.get("address")]
    if not crypto:
        todo.append("support: no crypto addresses filled: crypto section hidden")

    support_md = out / "SUPPORT.md"
    if s_links or crypto:
        row = [card(f"support-{slug(l['label'])}", l["label"].upper(),
                    l.get("caption") or re.sub(r"^https?://(www\.)?", "", l["url"]).split("/")[0],
                    l.get("logo", "heart"), l["url"], primary=i == 0)
               for i, l in enumerate(s_links)]
        if crypto:
            row.append(card("support-crypto", "CRYPTO", " · ".join(c["coin"] for c in crypto),
                            COIN_LOGOS.get(crypto[0]["coin"].upper(), "heart"), "SUPPORT.md#crypto", primary=not s_links))
        sections.append(("Support", [sup.get("intro", "").strip(), " ".join(row),
                                     '<sub><a href="SUPPORT.md">all options and addresses → SUPPORT.md</a></sub>']))
        support_md.write_text(support_page(cfg, s_links, crypto, assets, svg2, pic, todo, written, ci))
    elif support_md.exists() and GENERATED in support_md.read_text():
        support_md.unlink()

    for i, (title, blocks) in enumerate(sections, 1):
        name = f"label-{slug(title)}"
        svg2(name, lambda t, i=i, title=title: label_svg(title, t, num=i))
        md += [pic(name, title), ""]
        for block in filter(None, blocks):
            md += [block, ""]

    snake = cfg.get("extras", {}).get("snake", False)
    workflow = out / ".github" / "workflows" / "snake.yml"
    if snake:
        raw = f"https://raw.githubusercontent.com/{login}/{login}/output"
        md += [f'<picture><source media="(prefers-color-scheme: dark)" srcset="{raw}/snake-dark.svg">'
               f'<img src="{raw}/snake-light.svg" alt="Contribution graph eaten by a pixel snake"></picture>', ""]
        workflow.parent.mkdir(parents=True, exist_ok=True)
        workflow.write_text(SNAKE_WORKFLOW)
    elif workflow.exists() and GENERATED in workflow.read_text():
        workflow.unlink()

    # refresh live values on a schedule while any spec row uses them
    live_wf = out / ".github" / "workflows" / "live.yml"
    if any(r.get("live") for r in cfg.get("spec", [])):
        live_wf.parent.mkdir(parents=True, exist_ok=True)
        live_wf.write_text(live_workflow(cfg.get("extras", {}).get("live_cron", "17 4 * * *")))
    elif live_wf.exists() and GENERATED in live_wf.read_text():
        live_wf.unlink()

    svg2("eof", lambda t: label_svg("EOF", t))
    md += [pic("eof", "EOF"), "", "</div>", ""]
    (out / "README.md").write_text("\n".join(md))
    write_funding(out, login, sup, s_links, crypto)
    for f in assets.iterdir():  # drop assets nothing references any more
        if f.name not in written:
            f.unlink()
    return todo


def support_page(cfg, s_links, crypto, assets, svg2, pic, todo, written, ci=False) -> str:
    svg2("support-header", lambda t: header_svg("SUPPORT", "Thank you for backing open source", t))
    md = [MARK, "", '<div align="center">', "", pic("support-header", "Support"), "", "</div>", "",
          "Everything I publish is free and open source. Support buys time to maintain it, "
          "write documentation and build new tools. Thank you for considering it.", ""]
    if s_links:
        md += ["## Platforms", ""]
        md += [f"- **[{l['label']}]({l['url']})**" + (f" · {l['note']}" if l.get("note") else "") for l in s_links]
        md += [""]
    if crypto:
        md += ["## Crypto", "",
               "> **Send only the listed coin on the listed network.** Crypto transfers are irreversible: "
               "after pasting, compare the first and last characters of the address.", ""]
        for c in crypto:
            md += [f"### {c['coin']}", "", f"Network: **{c.get('network', c['coin'])}**", "", "```text", c["address"], "```", ""]
            name = f"qr-{slug(c['coin'])}.svg"
            path = assets / name
            qr = None if ci and path.exists() else qr_svg(c["address"])
            if qr is not None:
                path.write_text(str(qr))
            elif path.exists():  # keep the committed code: CI runners have no qrencode
                todo.append("qrencode not found: reusing existing QR codes") if not ci else None
            else:
                todo.append("qrencode not found: QR codes skipped")
                continue
            written.add(name)
            width = qr.w if qr else re.search(r'width="(\d+)"', path.read_text())[1]
            md += ["<details><summary>QR code</summary>", "<br>", "",
                   f'<img src="assets/{name}" width="{width}" alt="QR code for the {esc(c["coin"])} address">', "",
                   "</details>", ""]
    md += ["## Other ways to help", "",
           "- Star the repositories you find useful",
           "- Report bugs, suggest features, send pull requests",
           "- Tell someone who might need these tools", ""]
    return "\n".join(md)


def write_funding(out, login, sup, s_links, crypto):
    """FUNDING.yml drives the Sponsor button on the repository page."""
