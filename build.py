def render_markdown(text: str, offline: bool, cache: dict):
    """GitHub's own renderer (cached by content, the API allows 60 calls/hour), else mini_markdown."""
    key = hashlib.sha256(text.encode()).hexdigest()
    if key in cache:
        return cache[key], "GitHub API"
    if not offline:
        req = urllib.request.Request(
            "https://api.github.com/markdown", data=json.dumps({"text": text, "mode": "markdown"}).encode(),
            headers={"Accept": "application/vnd.github+json", "User-Agent": "profile-build"})
        try:
            with urllib.request.urlopen(req, timeout=15) as r:
                cache[key] = r.read().decode()
                return cache[key], "GitHub API"
        except OSError:
            pass
    return mini_markdown(text), "offline renderer"


def mini_markdown(text: str) -> str:
    """Just enough Markdown for the generated files when the API is unreachable."""
    def inline(s):
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', s)

    out, para, lines, i = [], [], text.splitlines(), 0

    def flush():
        if para:
            out.append("<p>" + inline("\n".join(para)) + "</p>")
            para.clear()

    while i < len(lines):
        line = lines[i]
        if line.startswith("```"):
            flush()
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append("<pre><code>" + esc("\n".join(lines[i + 1:j])) + "</code></pre>")
            i = j + 1
            continue
        if m := re.match(r"(#{1,6})\s+(.*)", line):
            flush()
            n = len(m[1])
            out.append(f'<h{n} id="{slug(m[2])}">{inline(m[2])}</h{n}>')
        elif line.startswith("- "):
            flush()
            items = []
            while i < len(lines) and lines[i].startswith("- "):
                items.append(f"<li>{inline(lines[i][2:])}</li>")
                i += 1
            out.append("<ul>" + "".join(items) + "</ul>")
            continue
        elif line.startswith("> "):
            flush()
            out.append(f"<blockquote><p>{inline(line[2:])}</p></blockquote>")
        elif not line.strip():
            flush()
        elif line.startswith(("<div", "</div", "<details", "</details", "<!--")):
            flush()
            out.append(line)
        else:
            para.append(line)
        i += 1
    flush()
    return "\n".join(out)


def build_avatars(cfg, todo):
    """Dithered avatars for GitHub settings → local/avatar/*.png and local/avatar.png."""
    src = ROOT / cfg["profile"].get("portrait", "art/portrait.png")
    try:
        from PIL import Image
    except ImportError:
        todo.append("Pillow not installed: avatar skipped (sudo pacman -S python-pillow)")
        return None
    if not src.exists():
        todo.append(f"{src.relative_to(ROOT)} missing: avatar skipped")
        return None
    outdir = LOCAL / "avatar"
    outdir.mkdir(parents=True, exist_ok=True)
    ramps = {2: [14, 236], 4: [14, 92, 164, 236]}

    def paint(grid, levels):
        img = Image.new("L", (len(grid), len(grid)))
        img.putdata([ramps[levels][v] for row in grid for v in row])
        return img

    variants = {
        "bayer-1bit": paint(dither(src, 115, 2), 2),
        "bayer-1bit-fine": paint(dither(src, 230, 2), 2),
        "bayer-4gray": paint(dither(src, 115, 4), 4),
        "floyd-1bit": Image.open(src).convert("L").resize((115, 115), Image.LANCZOS).convert("1")
                           .convert("L").point(lambda v: ramps[2][v > 127]),
    }
    for name, img in variants.items():
        img.resize((920, 920), Image.NEAREST).save(outdir / f"{name}.png", optimize=True)
    chosen = cfg["profile"].get("avatar_style", "bayer-4gray")
    if chosen not in variants:
        todo.append(f"profile.avatar_style {chosen!r} unknown: using bayer-4gray")
        chosen = "bayer-4gray"
    shutil.copy(outdir / f"{chosen}.png", LOCAL / "avatar.png")
    return list(variants), chosen


def build_stand(cfg, todo, avatars, chosen, offline):
    docs, engines, used = {}, set(), set()
    cache_file = LOCAL / ".markdown-cache.json"
    try:
        cache = json.loads(cache_file.read_text())
    except (OSError, ValueError):
        cache = {}
    for data, folder, prefix in (("real", ROOT, "../"), ("demo", LOCAL / "demo", "demo/")):
        for doc in ("README", "SUPPORT"):
            f = folder / f"{doc}.md"
            if not f.exists():
                docs[f"{data}:{doc}"] = None
                continue
            text = f.read_text()
            used.add(hashlib.sha256(text.encode()).hexdigest())
            body, engine = render_markdown(text, offline, cache)
            engines.add(engine)
            docs[f"{data}:{doc}"] = re.sub(r'(src|srcset)="(?:\./)?assets/', rf'\1="{prefix}assets/', body)
    cache_file.write_text(json.dumps({k: v for k, v in cache.items() if k in used}))
    engine = " + ".join(sorted(engines)) or "nothing to render"
    p = cfg["profile"]
    links = cfg.get("links", {})
    profile = {
        "name": p.get("name", ""), "login": p["login"], "bio": p.get("bio", ""),
        "links": [links[k] for k in ("website", "telegram", "email") if links.get(k)],
        "avatar": "avatar.png" if avatars else None, "avatars": avatars, "chosen": chosen,
    }
    page = (STAND.replace("__LOGO__", logo_svg("PROFILE STAND"))
            .replace("__DOCS__", json.dumps(docs).replace("</", "<\\/"))
            .replace("__PROFILE__", json.dumps(profile).replace("</", "<\\/"))
            .replace("__TODO__", json.dumps(sorted(set(todo))).replace("</", "<\\/"))
            .replace("__BUILD__", esc(f"{datetime.now():%Y-%m-%d %H:%M} · {engine}")))
    (LOCAL / "preview.html").write_text(page)
    return engine


