def svg(w: int, h: int, label: str, body: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
            f'shape-rendering="crispEdges" role="img" aria-label="{label}"><title>{label}</title>{body}</svg>\n')


def text(s: str, x: float, cap_top: float, scale: int, fill: str, family: str = "tiny5") -> str:
    """Pixel text. For Tiny5 `cap_top` is where capitals start; for kanji it is the top of the glyph box."""
    _, _, pts = text_pixels(s, family)
    oy = cap_top - (scale if family == "tiny5" else 0)
    return f'<path d="{svg_path(pts, scale, x, oy)}" fill="{fill}"/>' if pts else ""


def name_plate(p: dict, c: dict) -> str:
    """The name in large pixel capitals."""
    name = p["name"].upper()
    w = text_width(name, "tiny5") * 5
    return svg(w, 30, p["name"], text(name, 0, 4, 5, c["text"]))


def header(label: str, kanji: str, c: dict) -> str:
    """A small heading: the kanji in vermilion, then the label."""
    w = 22 + text_width(label.upper(), "tiny5") * 2
    return svg(w, 16, label, text(kanji, 0, 0, 1, c["shu"], "dotgothic") + text(label.upper(), 22, 3, 2, c["text"]))


def themed(base: str, alt: str) -> str:
    """<picture> that follows the viewer's theme; files are assets/gen/{base}-dark.svg / -light.svg."""
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="assets/gen/{base}-dark.svg">'
            f'<img src="assets/gen/{base}-light.svg" alt="{alt}"></picture>')


def icon(base: str) -> str:
    """An inline stack icon; with -Light and -Dark files it follows the viewer's theme."""
    light, dark = ROOT / f"assets/icons/{base}-Light.svg", ROOT / f"assets/icons/{base}-Dark.svg"
    img = lambda f: f'<img src="assets/icons/{f}" width="20" height="20" align="absmiddle">'
    if light.exists() and dark.exists():
        return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="assets/icons/{base}-Dark.svg">'
                f'{img(f"{base}-Light.svg")}</picture>')
    return img(f"{base}.svg")


def notched(x: int, y: int, w: int, h: int, n: int = 2) -> str:
    """A rectangle with stepped pixel corners, as a path."""
    a, b = n, 2 * n
    return (f"M{x + b} {y}H{x + w - b}V{y + a}H{x + w - a}V{y + b}H{x + w}V{y + h - b}H{x + w - a}V{y + h - a}"
            f"H{x + w - b}V{y + h}H{x + b}V{y + h - a}H{x + a}V{y + h - b}H{x}V{y + b}H{x + a}V{y + a}H{x + b}Z")


def button(e: dict, c: dict) -> str:
    """A compact pixel button: icon and label in a thin notched frame; the whole picture is the link."""
    label = e["label"].upper()
    h, icon_x = 26, 7
    text_x = icon_x + (16 + 7 if e.get("icon") else 0)
    w = text_x + text_width(label, "tiny5") * 2 + 9
    body = (f'<path d="{notched(0, 0, w, h, 1)}" fill="{c["line"]}"/>'
            f'<path d="{notched(1, 1, w - 2, h - 2, 1)}" fill="{c["panel"]}"/>')
    if e.get("icon"):
        src = (ROOT / f"assets/icons/{e['icon']}.svg").read_text()
        inner = src[src.index(">") + 1:src.rindex("</svg>")]
        body += f'<svg x="{icon_x}" y="5" width="16" height="16" viewBox="0 0 256 256" shape-rendering="auto">{inner}</svg>'
    body += text(label, text_x, 8, 2, c["text"])
    return svg(w, h, f'{e["label"]}: {e.get("text", "")}', body)


def links(entries: list[dict]) -> str:
    """Buttons for entries with a url; entries without one (wallets) as a copyable line below."""
    out = " ".join(f'<a href="{e["url"]}">{themed(f"btn-{e["label"].lower().replace(" ", "-")}", e["label"])}</a>'
                   for e in entries if e.get("url"))
    plain = [(icon(e["icon"]) + " " if e.get("icon") else "") + f'<b>{e["label"]}</b> <code>{e["text"]}</code>'
             for e in entries if not e.get("url")]
    return "<br>\n".join(([out] if out else []) + plain)


