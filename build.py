def write_preview(readme: str, p: dict, poster: str) -> None:
    """preview.html: the README inside a GitHub-like profile page, with theme, phone view and poster
    switches. Local only (it is in .gitignore); the sidebar and repositories load from the GitHub API."""
    names = sorted(f.stem for f in (ROOT / "assets/posters").glob("*.gif"))
    buttons = "".join(f'<button data-v="{n}">{n}</button>' for n in names)
    html = (PREVIEW.replace("@@README@@", readme.replace(MARK, "")).replace("@@POSTERS@@", buttons)
            .replace("@@POSTER@@", Path(poster).stem).replace("@@LOGIN@@", p["login"]).replace("@@NAME@@", p["name"]))
    (ROOT / "preview.html").write_text(html)


def main() -> None:
    cfg = tomllib.loads((ROOT / "profile.toml").read_text())
    p = cfg["profile"]
    contacts, projects = cfg.get("contacts", []), cfg.get("projects", [])
    poster = f'assets/posters/{p.get("poster", "tsuki")}.gif'
    if not (ROOT / poster).exists():
        raise SystemExit(f"{poster} not found: run python3 poster.py, or pick another poster in profile.toml")

    GEN.mkdir(parents=True, exist_ok=True)
    for old in GEN.glob("*.svg"):
        old.unlink()
    for theme, c in THEMES.items():
        (GEN / f"name-{theme}.svg").write_text(name_plate(p, c))
        for key, (label, kanji) in SECTIONS.items():
            (GEN / f"h-{key}-{theme}.svg").write_text(header(label, kanji, c))
        for e in contacts:
            if e.get("url"):
                (GEN / f'btn-{e["label"].lower().replace(" ", "-")}-{theme}.svg').write_text(button(e, c))

    def section(key: str, body: str) -> str:
        """Heading in a margin-less <div> and the body straight under it. No blank lines: in markdown a
        blank line ends the HTML block and GitHub starts a new paragraph, which shows as a gap."""
        return f'<div>{themed(f"h-{key}", SECTIONS[key][0])}</div>\n{body}'

    about = " ".join(p["about"].split())
    stack = "<br>\n".join(
        " ".join(icon(i) for i in s.get("icons", [])) + f' <b>{s["name"]}</b>, {s["note"]}' for s in cfg["stack"]
    )
    items = "\n".join(
        f'<li><a href="https://github.com/{p["login"]}/{x.get("repo", x["name"])}"><b>{x["name"]}</b></a>, '
        f'{x["description"]}</li>' for x in projects
    )
    parts = [f"<p>{themed('name', p['name'])}</p>", f"<p>{about}</p>",
             section("stack", f"<p>\n{stack}\n</p>"), section("projects", f"<ul>\n{items}\n</ul>")]
    if contacts:
        parts.append(section("contact", f"<p>{links(contacts)}</p>"))
    right = "\n\n".join(parts)

    out = f"""{MARK}

<table><tr>
<td valign="top" width="400"><img src="{poster}" width="384" alt="{p.get("poster_alt") or POSTER_ALT.get(p.get("poster", "tsuki"), "")}"></td>
<td valign="top">

{right}

</td>
</tr></table>
"""
    (ROOT / "README.md").write_text(out)
    write_preview(out, p, poster)
    print(f"README.md: poster {poster}, {len(cfg['stack'])} stack items, {len(projects)} projects, "
          f"{len(contacts)} contacts; preview.html for a local look")
    todo = [e["label"] for e in contacts if "your" in (e.get("text", "") + e.get("url", "")).lower()]
    if todo:
        print("  placeholders left in profile.toml:", ", ".join(todo))


if __name__ == "__main__":
    main()
