def export(dest=ROOT / "upload"):
    """Fresh copy of the publishable files in upload/, for GitHub → Add file → Upload files."""
    shutil.rmtree(dest, ignore_errors=True)
    dest.mkdir()
    for name in PUBLISH:
        src = ROOT / name
        if src.is_dir():
            shutil.copytree(src, dest / name, ignore=shutil.ignore_patterns("__pycache__"))
        elif src.exists():
            shutil.copy2(src, dest / name)
    return sum(1 for f in dest.rglob("*") if f.is_file())


