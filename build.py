#!/usr/bin/env python3
"""Builds README.md from profile.toml. Standard library only (Python 3.11+).

    python3 build.py
"""
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MARK = "<!-- generated by build.py from profile.toml: edit the config, not this file -->"


def main() -> None:
    cfg = tomllib.loads((ROOT / "profile.toml").read_text())
    p = cfg["profile"]
    about = " ".join(p["about"].split())
    stack = "\n".join(f'<li><b>{s["name"]}</b>, {s["note"]}</li>' for s in cfg["stack"])
    projects = "\n".join(
        f'<li><a href="https://github.com/{p["login"]}/{x["name"]}"><b>{x["name"]}</b></a>, {x["description"]}</li>'
        for x in cfg["projects"]
    )
    out = f"""{MARK}

<table><tr>
<td valign="top" width="340"><img src="assets/poster.svg" width="320" alt=""></td>
<td valign="top">

<h3>Hi, I'm {p["name"]}</h3>
<p>{about}</p>

<h3>Stack</h3>
<ul>
{stack}
</ul>

<h3>Projects</h3>
<ul>
{projects}
</ul>

</td>
</tr></table>
"""
    (ROOT / "README.md").write_text(out)
    print(f"README.md: {len(cfg['stack'])} stack items, {len(cfg['projects'])} projects")


if __name__ == "__main__":
    main()
