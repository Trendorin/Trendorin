def arch_kernel():
    """Newest core/linux on Arch, formatted the way `uname -r` prints it: 7.2.6-arch2-1."""
    req = urllib.request.Request("https://archlinux.org/packages/core/x86_64/linux/json/",
                                 headers={"User-Agent": "profile-build (github.com/Trendorin)"})
    with urllib.request.urlopen(req, timeout=10) as r:
        pkg = json.load(r)
    version = re.sub(r"\.(arch\d+)$", r"-\1", pkg["pkgver"])  # 7.2.6.arch2 → 7.2.6-arch2
    return f"Linux {version}-{pkg['pkgrel']}"


