def live_values(cfg, offline, todo):
    """Fetch every live source the config uses; fall back to the cached value on failure."""
    try:
        cache = json.loads(LIVE_FILE.read_text())
    except (OSError, ValueError):
        cache = {}
    for name in {r["live"] for r in cfg.get("spec", []) if r.get("live")}:
        if name not in LIVE_SOURCES:
            todo.append(f"unknown live source {name!r} (known: {', '.join(LIVE_SOURCES)})")
        elif not offline:
            try:
                cache[name] = LIVE_SOURCES[name]()
            except (OSError, ValueError, KeyError) as e:
                todo.append(f"live {name}: fetch failed ({type(e).__name__}), kept {cache.get(name, 'nothing')}")
    text = json.dumps(cache, indent=2, sort_keys=True) + "\n"
    if cache and (not LIVE_FILE.exists() or LIVE_FILE.read_text() != text):
        LIVE_FILE.write_text(text)
    return cache


