#!/usr/bin/env python3
"""Builds README.md, the stack list and the project cards from profile.toml.

    python3 build.py

Needs fonttools, uharfbuzz and rsvg-convert (see engine.py). The banner comes from
banner.py and only has to be rebuilt when you want a different picture.
"""
from __future__ import annotations

import re
import tomllib
from pathlib import Path

from engine import font, svg, text, themes, wrap, write

ROOT = Path(__file__).resolve().parent
ASSETS = ROOT / "assets"
CARD_W, CARD_H = 420, 124
MARK = "<!-- generated by build.py from profile.toml: edit the config, not this file -->"
TH = themes("#5b43e0", "#a397ff")


def read_icon(base: str, theme: str) -> tuple[str, str]:
    for name in (f"{base}-{theme.capitalize()}", base):
        f = ASSETS / "icons" / f"{name}.svg"
        if f.exists():
            raw = f.read_text()
            vb = re.search(r'viewBox="([^"]+)"', raw).group(1)
            return vb, re.sub(r"^<svg[^>]*>|</svg>\s*$", "", raw.strip())
    raise SystemExit(f"icon not found: {base}")


def unique_ids(inner: str, prefix: str) -> str:
    for i in set(re.findall(r'id="([^"]+)"', inner)):
        inner = inner.replace(f'id="{i}"', f'id="{prefix}-{i}"').replace(f"#{i})", f"#{prefix}-{i})")
    return inner


def stack_svg(rows: list[dict], t) -> str:
    row_h, size = 46, 32
    body = []
    for i, r in enumerate(rows):
        y = i * row_h
        vb, inner = read_icon(r["icon"], t.name)
        body.append(f'<svg x="0" y="{y + 4}" width="{size}" height="{size}" viewBox="{vb}">{unique_ids(inner, f"s{i}{t.name}")}</svg>')
        body.append(text(r["name"], 48, y + 18, 15, t.title, "semibold"))
        body.append(text(r["note"], 48, y + 35, 12.5, t.muted))
    return svg(300, len(rows) * row_h - 6, "".join(body), ", ".join(r["name"] for r in rows))


def card_svg(p: dict, t) -> str:
    slug = Path(p["logo"]).stem
    raw = (ASSETS / "projects" / p["logo"]).read_text()
    vb = re.search(r'viewBox="([^"]+)"', raw).group(1)
    inner = unique_ids(re.sub(r"^<svg[^>]*>|</svg>\s*$", "", raw.strip()), f"{slug}{t.name}")
    body = [f'<rect x=".5" y=".5" width="{CARD_W - 1}" height="{CARD_H - 1}" rx="12" fill="{t.card}" stroke="{t.border}"/>',
            f'<svg x="20" y="20" width="56" height="56" viewBox="{vb}">{inner}</svg>',
            text(p["name"], 92, 38, 17, t.title, "semibold")]
    for i, line in enumerate(wrap(p["description"], 13.5, CARD_W - 112)[:2]):
        body.append(text(line, 92, 60 + 19 * i, 13.5, t.text))
    x = 20
    for tag in p.get("tags", []):
        w = font("medium").width(tag, 11.5) + 18
        body.append(f'<rect x="{x:g}" y="{CARD_H - 36}" width="{w:g}" height="22" rx="11" fill="{t.tint}"/>')
        body.append(text(tag, x + w / 2, CARD_H - 21, 11.5, t.accent, "medium", "middle"))
        x += w + 8
    return svg(CARD_W, CARD_H, "".join(body), f'{p["name"]}: {p["description"]}')


def picture(name: str, alt: str, attrs: str = "") -> str:
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="assets/{name}-dark.svg">'
            f'<img src="assets/{name}-light.svg" alt="{alt}"{attrs}></picture>')


def main() -> None:
    cfg = tomllib.loads((ROOT / "profile.toml").read_text())
    p = cfg["profile"]
    for old in ASSETS.glob("card-*.svg"):
        old.unlink()
    write(ASSETS, "stack", {k: stack_svg(cfg["stack"], t) for k, t in TH.items()})
    cards = []
    for proj in cfg["projects"]:
        slug = Path(proj["logo"]).stem
        write(ASSETS, f"card-{slug}", {k: card_svg(proj, t) for k, t in TH.items()})
        cards.append(f'<a href="https://github.com/{p["login"]}/{proj["name"]}">'
                     + picture(f"card-{slug}", proj["name"], ' width="49%"') + "</a>")
    rows = [" ".join(cards[i:i + 2]) for i in range(0, len(cards), 2)]
    out = [MARK, "",
           f'<img src="assets/banner.svg" width="100%" alt="{p["login"]}">', "",
           f'Hi, I\'m **{p["name"]}**.', "", p["about"].strip(), "",
           "### Stack", "", picture("stack", "Stack"), "",
           "### Projects", "", *["\n".join(rows)], "",
           '<sub>Stack icons from <a href="https://github.com/tandpfun/skill-icons">skill-icons</a> (MIT).</sub>', ""]
    (ROOT / "README.md").write_text("\n".join(out))
    print(f"README.md: {len(cfg['stack'])} stack rows, {len(cards)} projects")


if __name__ == "__main__":
    main()
